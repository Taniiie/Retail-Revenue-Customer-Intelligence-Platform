"""
RFM Analytics & Customer Segmentation Engine
Target: Retail Revenue & Customer Intelligence Platform

DATA TRANSPARENCY NOTICE:
All analysis performed by this script is based on 100% SYNTHETIC transactional data 
generated for portfolio analytics and data pipeline validation.

METHODOLOGY & SEGMENTATION RULES:
--------------------------------------------------------------------------------
1. Recency (R): Days elapsed between the analysis reference date (max dataset order date + 1 day) 
   and the customer's latest completed purchase. (R_Score 5 = Most Recent, 1 = Least Recent).
2. Frequency (F): Count of distinct completed/shipped orders placed by the customer. 
   Categorized into 5 discrete percentile rank buckets.
3. Monetary (M): Total net revenue generated by the customer. Categorized into 5 quantiles.

CUSTOMER PERSONA SEGMENTATION RULES:
- Champions          : R >= 4, F >= 4, M >= 4  (High recency, high frequency, high spend)
- Loyal Customers    : R >= 3, F >= 3, M >= 3  (Consistent repeat buyers, active)
- Potential Loyalists: R >= 4, F <= 2, M >= 2  (Recent buyers with growth potential)
- At Risk            : R <= 2, F >= 3, M >= 3  (High historical spend/freq, but inactive recently)
- Hibernating        : R <= 2, F <= 2, M >= 2  (Low recency, low frequency, moderate spend)
- Lost Customers     : R <= 2, F <= 2, M == 1  (Lowest engagement across all dimensions)
- Needs Attention    : Remaining combinations not captured above (mid-range engagement).
--------------------------------------------------------------------------------
"""

import os
import sqlite3
import pandas as pd
import numpy as np
from datetime import datetime

PROJECT_ROOT = os.path.dirname(os.path.dirname(__file__))
DB_PATH = os.path.join(PROJECT_ROOT, "data", "retail_intelligence.db")
PROCESSED_DIR = os.path.join(PROJECT_ROOT, "data", "processed")

os.makedirs(PROCESSED_DIR, exist_ok=True)

def compute_rfm_segments():
    print("[INFO] Initializing RFM Analysis Engine...")
    conn = sqlite3.connect(DB_PATH)

    # 1. Extract Customer Aggregates from database
    query = """
    SELECT 
        c.customer_id,
        c.first_name || ' ' || c.last_name AS customer_name,
        c.email,
        c.city,
        c.state,
        c.country,
        c.signup_date,
        COUNT(DISTINCT o.order_id) AS frequency,
        MAX(o.order_date) AS last_order_date,
        SUM(o.total_amount) AS monetary
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    WHERE o.order_status IN ('Completed', 'Shipped')
    GROUP BY c.customer_id, c.first_name, c.last_name, c.email, c.city, c.state, c.country, c.signup_date
    """
    
    df_rfm = pd.read_sql_query(query, conn)
    conn.close()

    # Define analysis reference date (1 day after max dataset order date)
    max_order_date = pd.to_datetime(df_rfm["last_order_date"]).max()
    reference_date = max_order_date + pd.Timedelta(days=1)
    
    print(f"  Max Dataset Order Date: {max_order_date.strftime('%Y-%m-%d')}")
    print(f"  Analysis Reference Date: {reference_date.strftime('%Y-%m-%d')}")

    # 2. Calculate Recency (Days since last order)
    df_rfm["last_order_datetime"] = pd.to_datetime(df_rfm["last_order_date"])
    df_rfm["recency"] = (reference_date - df_rfm["last_order_datetime"]).dt.days

    # 3. Calculate Quantile Scores (1 to 5)
    # Recency Score: Lower recency days -> Higher score (5)
    df_rfm["r_score"] = pd.qcut(df_rfm["recency"], q=5, labels=[5, 4, 3, 2, 1]).astype(int)

    # Frequency Score: Discrete rank quantile
    df_rfm["f_score"] = pd.qcut(df_rfm["frequency"].rank(method="first"), q=5, labels=[1, 2, 3, 4, 5]).astype(int)

    # Monetary Score: Higher monetary spend -> Higher score (5)
    df_rfm["m_score"] = pd.qcut(df_rfm["monetary"], q=5, labels=[1, 2, 3, 4, 5]).astype(int)

    # Composite RFM Score String (e.g., '555', '111') and Average Score
    df_rfm["rfm_score_str"] = df_rfm["r_score"].astype(str) + df_rfm["f_score"].astype(str) + df_rfm["m_score"].astype(str)
    df_rfm["rfm_score_avg"] = round((df_rfm["r_score"] + df_rfm["f_score"] + df_rfm["m_score"]) / 3.0, 2)

    # 4. Apply Persona Mapping Logic
    def map_rfm_persona(row):
        r, f, m = row["r_score"], row["f_score"], row["m_score"]
        
        if r >= 4 and f >= 4 and m >= 4:
            return "Champions"
        elif r >= 3 and f >= 3 and m >= 3:
            return "Loyal Customers"
        elif r >= 4 and f <= 2 and m >= 2:
            return "Potential Loyalists"
        elif r <= 2 and f >= 3 and m >= 3:
            return "At Risk"
        elif r <= 2 and f <= 2 and m >= 2:
            return "Hibernating"
        elif r <= 2 and f <= 2 and m == 1:
            return "Lost Customers"
        else:
            return "Needs Attention"

    df_rfm["rfm_segment"] = df_rfm.apply(map_rfm_persona, axis=1)

    # Clean date strings
    df_rfm["last_order_date"] = df_rfm["last_order_datetime"].dt.strftime("%Y-%m-%d")
    df_rfm = df_rfm.drop(columns=["last_order_datetime"])

    # 5. Save RFM Analytical Artifact
    export_path = os.path.join(PROCESSED_DIR, "customer_rfm.csv")
    df_rfm.to_csv(export_path, index=False)
    print(f"[SUCCESS] Exported customer RFM analytical artifact: {export_path} ({len(df_rfm)} customers)")

    # 6. Generate Summary Segment Breakdown Report
    summary_df = df_rfm.groupby("rfm_segment").agg(
        customer_count=("customer_id", "count"),
        avg_recency_days=("recency", "mean"),
        avg_frequency_orders=("frequency", "mean"),
        avg_monetary_spend=("monetary", "mean"),
        total_segment_revenue=("monetary", "sum")
    ).reset_index()

    total_revenue = df_rfm["monetary"].sum()
    total_cust = len(df_rfm)
    
    summary_df["pct_of_customers"] = round((summary_df["customer_count"] / total_cust) * 100, 2)
    summary_df["pct_of_revenue"] = round((summary_df["total_segment_revenue"] / total_revenue) * 100, 2)
    summary_df = summary_df.sort_values(by="total_segment_revenue", ascending=False)

    print("\n==================================================")
    print("             RFM SEGMENTATION SUMMARY             ")
    print("==================================================")
    for _, r in summary_df.iterrows():
        print(f" Segment: {r['rfm_segment']:<20} | Cust: {r['customer_count']:>4} ({r['pct_of_customers']:>5}%) | Rev: ${r['total_segment_revenue']:>10,.2f} ({r['pct_of_revenue']:>5}%) | Avg Spend: ${r['avg_monetary_spend']:>7,.2f}")
    print("==================================================\n")

    # Export customer summary artifact
    summary_export_path = os.path.join(PROCESSED_DIR, "customer_summary.csv")
    summary_df.to_csv(summary_export_path, index=False)

    return df_rfm, summary_df

if __name__ == "__main__":
    compute_rfm_segments()
